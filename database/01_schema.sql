BEGIN;
CREATE TABLE IF NOT EXISTS officers (
    id varchar(25) PRIMARY KEY,
    first_name varchar(255), last_name varchar(255),
    force_name varchar(255), rank_name varchar(255), force_id varchar(255),
    email varchar(255), password_hash varchar(255),
    role varchar(255) NOT NULL DEFAULT 'OFFICER',
    active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS defense_registry (
    document_id varchar(255) PRIMARY KEY,
    force_name varchar(255), rank_name varchar(255),
    force_id varchar(255) UNIQUE, email varchar(255), active boolean DEFAULT true
);
CREATE TABLE IF NOT EXISTS citizens (
    document_id varchar(255) PRIMARY KEY,
    first_name varchar(255), last_name varchar(255),
    birth_date date, birth_place varchar(255),
    issue_date date, issue_place varchar(255),
    rh varchar(255), blood_group varchar(255), height_cm integer,
    required boolean NOT NULL DEFAULT false
);
CREATE TABLE IF NOT EXISTS auth_sessions (
    token_hash varchar(64) PRIMARY KEY,
    officer_id varchar(25) REFERENCES officers(id),
    expires_at timestamp(6) with time zone
);
CREATE TABLE IF NOT EXISTS lookup_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    officer_id varchar(255), citizen_id varchar(255),
    outcome varchar(255), occurred_at timestamp(6) with time zone
);
CREATE INDEX IF NOT EXISTS idx_audit_officer_date ON lookup_audit(officer_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_session_expiration ON auth_sessions(expires_at);
CREATE INDEX IF NOT EXISTS idx_citizen_required ON citizens(required);
CREATE TABLE IF NOT EXISTS status_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    officer_id varchar(255), citizen_id varchar(255),
    previous_required boolean NOT NULL, new_required boolean NOT NULL,
    occurred_at timestamp(6) with time zone
);
CREATE TABLE IF NOT EXISTS citizen_registration_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    officer_id varchar(255) NOT NULL,
    citizen_id varchar(255) NOT NULL,
    occurred_at timestamp(6) with time zone NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_citizen_registration_actor_date ON citizen_registration_audit(officer_id,occurred_at DESC);
COMMIT;
