-- HU3: auditoría de altas para bases PostgreSQL existentes.
-- Idempotente, no modifica registros ciudadanos existentes.
BEGIN;
CREATE TABLE IF NOT EXISTS citizen_registration_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    officer_id varchar(255) NOT NULL,
    citizen_id varchar(255) NOT NULL,
    occurred_at timestamp(6) with time zone NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_citizen_registration_actor_date
    ON citizen_registration_audit(officer_id,occurred_at DESC);
COMMIT;
